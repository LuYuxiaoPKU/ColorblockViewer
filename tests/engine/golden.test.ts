function errMessage(e: unknown): string {
  const m = e instanceof Error ? e.message : String(e);
  return m.includes('\n') ? m.slice(0, m.indexOf('\n')) : m;
}

describe('golden', () => {
  it.each(CASES.map(([src], i) => [i, src] as const))(
    'case %i',
    (_i, src) => {
      const expectd = CASES[_i][1];
      try {
        const got = evalForTest(src);
        if (typeof expectd === 'number') {
          expect(got, `[${src}] 期望 ${expectd}, 实际 ${got}`).toBe(expectd);
        } else {
          throw new Error(`[${src}] 期望错误 "${expectd.slice(0, 40)}...", 实际得到值 ${got}`);
        }
      } catch (e) {
        if (typeof expectd === 'string') {
          const m = errMessage(e);
          // 前缀匹配（golden 输出可能截断长消息）
          const want = expectd.length > 60 ? expectd.slice(0, 60) : expectd;
          expect(m.startsWith(want), `[${src}] 期望错误 "${want}", 实际 "${m}"`).toBe(true);
        } else {
          throw e;
        }
      }
    },
  );
});
