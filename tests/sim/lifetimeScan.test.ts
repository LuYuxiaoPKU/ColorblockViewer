const N = 1 << 24;
const fr = Math.fround;

// —— 与 src/sim/kinematics.ts 的 L.* 逐字一致（f = n/2^24 精确 float）——
const base = (n: number) => Math.trunc(fr(4.0 / fr(fr(fr(0.9) * n) + fr(0.1))));
const squid = (n: number) => Math.trunc(fr(6.0 / fr(fr(fr(0.8) * n) + fr(0.2))));
const rev = (n: number) => 60 + Math.trunc(fr(2.0 * n));
const div = (N0: number) => (n: number) => Math.trunc(N0 / (n * 0.8 + 0.2));
const crit = (n: number) => Math.max(Math.trunc(6.0 / (n * 0.8 + 0.6)), 1);
const ash = (N0: number, s: number) => (n: number) =>
  Math.max(Math.trunc((N0 / (n * 0.8 + 0.2)) * fr(s)), 1);

